#!/usr/bin/env python3
"""Build placements.js from the learner-story cards on track-record.html.

The track-record page is the site's placement memory: when a new placed
learner is added there, re-run this script and commit the regenerated
placements.js — every course page's "Placements & internships" strip
updates from the same data. No placement data is typed by hand here.

Usage: python3 tools/build_placements.py
"""
import json
import re
import html as html_lib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "track-record.html"
OUT = ROOT / "placements.js"

h = SRC.read_text(encoding="utf-8")
parts = re.split(r'<div class="persona">', h)[1:]
out = []
for p in parts:
    img = re.search(r'src="([^"]+)"', p)
    before = re.search(r'<b>Before:</b>(.*?)<br>', p)
    after = re.search(r'<b>After:</b>(.*?)</p>', p)
    if not (img and before and after):
        continue  # trainer feature boxes have no photo/before/after
    name = re.search(r'<h3>(.*?)</h3>', p).group(1).strip()
    fine = re.search(r'<p class="fine"[^>]*>(.*?)</p>', p, re.S).group(1)
    fine = html_lib.unescape(re.sub(r'<[^>]+>', '', fine)).strip()
    segs = [s.strip() for s in fine.split('\u00b7')]
    out.append({
        'name': html_lib.unescape(name),
        'photo': img.group(1).split('?')[0],
        'track': segs[0],
        'placed': segs[1] if len(segs) > 1 else '',
        'jump': segs[2] if len(segs) > 2 else '',
        'before': html_lib.unescape(re.sub(r'<[^>]+>', '', before.group(1))).strip(),
        'after': html_lib.unescape(re.sub(r'<[^>]+>', '', after.group(1))).strip(),
    })

OUT.write_text(
    '/* Generated by tools/build_placements.py from track-record.html — do not edit by hand. */\n'
    'window.NS_PLACEMENTS = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n',
    encoding='utf-8')
print(f'wrote {OUT} — {len(out)} placed learners')
